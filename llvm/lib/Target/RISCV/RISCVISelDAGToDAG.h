#ifndef LLVM_LIB_TARGET_RISCV_RISCVISELDAGTODAG_H
#define LLVM_LIB_TARGET_RISCV_RISCVISELDAGTODAG_H

#include "RISCV.h"
#include "RISCVTargetMachine.h"
#include "llvm/CodeGen/SelectionDAGISel.h"

// RISCV-specific code to select RISCV machine instructions for
// SelectionDAG operations.
namespace llvm {
class RISCVDAGToDAGISel : public SelectionDAGISel {
  const RISCVSubtarget *Subtarget = nullptr;

public:
  explicit RISCVDAGToDAGISel(RISCVTargetMachine &TargetMachine)
      : SelectionDAGISel(TargetMachine) {}

  StringRef getPassName() const override {
    return "RISCV DAG->DAG Pattern Instruction Selection";
  }

  bool runOnMachineFunction(MachineFunction &MF) override {
    Subtarget = &MF.getSubtarget<RISCVSubtarget>();
    bool Changed = SelectionDAGISel::runOnMachineFunction(MF);
#ifdef ESPERANTO
    optimizeMaskCopies(MF);
#endif
    return Changed;
  }

  void PostprocessISelDAG() override;
#ifdef ESPERANTO
  void PreprocessISelDAG() override;
#endif

  void Select(SDNode *Node) override;

  bool SelectInlineAsmMemoryOperand(const SDValue &Op, unsigned ConstraintID,
                                    std::vector<SDValue> &OutOps) override;

  bool SelectAddrFI(SDValue Addr, SDValue &Base);

  bool SelectSLOI(SDValue N, SDValue &RS1, SDValue &Shamt);
  bool SelectSROI(SDValue N, SDValue &RS1, SDValue &Shamt);
  bool SelectRORI(SDValue N, SDValue &RS1, SDValue &Shamt);
  bool SelectSLLIUW(SDValue N, SDValue &RS1, SDValue &Shamt);
  bool SelectSLOIW(SDValue N, SDValue &RS1, SDValue &Shamt);
  bool SelectSROIW(SDValue N, SDValue &RS1, SDValue &Shamt);
  bool SelectRORIW(SDValue N, SDValue &RS1, SDValue &Shamt);
  bool SelectFSRIW(SDValue N, SDValue &RS1, SDValue &RS2, SDValue &Shamt);

// Include the pieces autogenerated from the target description.
#include "RISCVGenDAGISel.inc"

private:
  void doPeepholeLoadStoreADDI();
  template <unsigned WIDTH> SDValue transform_LO(ConstantSDNode *N) {
    return CurDAG->getTargetConstant(N->getZExtValue() & ((1ull << WIDTH) - 1),
                                     SDLoc(N), MVT::i32);
  }
  template <unsigned WIDTH> SDValue transform_LOs(ConstantSDNode *N) {
    return CurDAG->getTargetConstant(SignExtend64(N->getZExtValue(), WIDTH),
                                     SDLoc(N), MVT::i32);
  }
private:
#ifdef ESPERANTO
  static const unsigned MAX_VECTOR_LANES = 8;
  // pre-pass to handle some custom lowerings 
  void doEsperantoRewrites();
  void esperantoRewrite(SDNode *N);
  // Special case some build vectors where optimized
  // implementations are possible.
  void esperantoBUILD_VECTOR(SDNode *N);
  void esperantoEXTRACT_VECTOR_ELT(SDNode *N);
  void esperantoINSERT_VECTOR_ELT(SDNode *N);
  // Convert remaining vectors shuffles to FSWIZZ_PS
  void esperantoVECTOR_SHUFFLE(SDNode *N);
  void esperantoVECTOR_SETCC(SDNode *N);
  // Handles memory operations that are vector or are not address space 0
  void esperantoMemop(MemSDNode *M, SDValue Value, SDValue Addr,
                      SDValue PassThru, SDValue Mask, ISD::LoadExtType Ext);
  // Handle et_masked_gather intrinsic
  void esperantoGather(MemIntrinsicSDNode *M);
  // Handle et_masked_scater intrinsic
  void esperantoScatter(MemIntrinsicSDNode *M);

  // post-pass over MachineIstrs, rewrite to improve handling of M0 implicit
  // mask operands
  void optimizeMaskCopies(MachineFunction &MF);
#endif
};
}

#endif
